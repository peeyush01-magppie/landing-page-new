/**
 * Generates src/data/indiaMap.js — a dotted map of India (dot grid + projection
 * constants) used by the <IndiaMap /> component.
 *
 * Boundary source: Natural Earth 1:10m admin-0 countries, India point-of-view
 * edition (official Indian boundaries, incl. all of J&K and Ladakh).
 *
 *   node scripts/generate-india-dots.mjs [path-to-local.geojson]
 */
import { readFile, writeFile } from 'node:fs/promises'

const SRC =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries_ind.geojson'

// Grid step in degrees of latitude (longitude step is corrected for latitude scale).
const STEP = 0.34
// Reference latitude for the equirectangular projection (keeps India's proportions natural).
const REF_LAT = 22
const PAD = 1.2 // degrees of padding around the bounds

const geo = JSON.parse(process.argv[2] ? await readFile(process.argv[2], 'utf8') : await (await fetch(SRC)).text())
const india = geo.features.find((f) => f.properties.ADM0_A3 === 'IND')
if (!india) throw new Error('India feature not found')

const polygons = india.geometry.type === 'Polygon' ? [india.geometry.coordinates] : india.geometry.coordinates

// Ray-casting point-in-ring test.
function inRing([x, y], ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
const inPolygon = (p, [outer, ...holes]) => inRing(p, outer) && !holes.some((h) => inRing(p, h))

// Bounds
let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity
for (const poly of polygons)
  for (const [lon, lat] of poly[0]) {
    minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon)
    minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat)
  }
minLon -= PAD; maxLon += PAD; minLat -= PAD; maxLat += PAD

const kx = Math.cos((REF_LAT * Math.PI) / 180)
const SCALE = 24 // svg units per degree of latitude
const width = (maxLon - minLon) * kx * SCALE
const height = (maxLat - minLat) * SCALE
const project = (lon, lat) => [(lon - minLon) * kx * SCALE, (maxLat - lat) * SCALE]

const round = (n) => Math.round(n * 10) / 10
const dots = []
const lonStep = STEP / kx
for (let lat = maxLat; lat >= minLat; lat -= STEP) {
  for (let lon = minLon; lon <= maxLon; lon += lonStep) {
    if (polygons.some((poly) => inPolygon([lon, lat], poly))) {
      const [x, y] = project(lon, lat)
      dots.push([round(x), round(y)])
    }
  }
}

// Small island groups (Andamans, Lakshadweep) can fall between grid points —
// give any polygon with no dots a single dot at its vertex average.
for (const poly of polygons) {
  const ring = poly[0]
  const [sx, sy] = ring.reduce(([a, b], [lon, lat]) => [a + lon, b + lat], [0, 0])
  const c = [sx / ring.length, sy / ring.length]
  const [cx, cy] = project(...c)
  const near = dots.some(([x, y]) => Math.hypot(x - cx, y - cy) < STEP * SCALE * 1.2)
  if (!near) {
    const area = Math.abs(ring.reduce((s, [x1, y1], i) => { const [x2, y2] = ring[(i + 1) % ring.length]; return s + x1 * y2 - x2 * y1 }, 0) / 2)
    if (area > 0.002) dots.push([round(cx), round(cy)])
  }
}

const out = `// AUTO-GENERATED by scripts/generate-india-dots.mjs — do not edit by hand.
// Boundary: Natural Earth 1:10m, India point-of-view edition (public domain).
export const MAP_WIDTH = ${round(width)}
export const MAP_HEIGHT = ${round(height)}
export const DOT_SPACING = ${round(STEP * SCALE)}

const MIN_LON = ${minLon}
const MAX_LAT = ${maxLat}
const KX = ${kx}
const SCALE = ${SCALE}

/** Project a [lon, lat] coordinate into map (SVG) space. */
export function project(lon, lat) {
  return [(lon - MIN_LON) * KX * SCALE, (MAX_LAT - lat) * SCALE]
}

/** Dot centres, [x, y] in map space. */
export const DOTS = ${JSON.stringify(dots)}
`
await writeFile(new URL('../src/data/indiaMap.js', import.meta.url), out)
console.log(`${dots.length} dots, ${round(width)} x ${round(height)}`)
